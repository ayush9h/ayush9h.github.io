import { readFileSync, writeFileSync } from "node:fs";

const SRC = "src/app/components/stack.tsx";
const OUT = "src/app/elements/stack-icons.ts";
const VARIANT = "light"; // tech-stack-icons' own default

const icons = JSON.parse(
  readFileSync("node_modules/tech-stack-icons/icons.json", "utf8"),
);

const used = [
  ...new Set(
    [...readFileSync(SRC, "utf8").matchAll(/icon:\s*"([^"]+)"/g)].map(
      (m) => m[1],
    ),
  ),
].sort();

const missing = used.filter((n) => !icons[n]?.svg?.[VARIANT]);
if (missing.length) {
  console.error(`Unknown icon name(s): ${missing.join(", ")}`);
  process.exit(1);
}

const entries = used
  .map(
    (n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n].svg[VARIANT])},`,
  )
  .join("\n");

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-stack-icons.mjs — do not edit by hand.\n` +
    `// ${used.length} "${VARIANT}" icons extracted from tech-stack-icons.\n\n` +
    `export const stackIcons: Record<string, string> = {\n${entries}\n};\n\n` +
    `export type StackIconName = keyof typeof stackIcons;\n`,
);

const kb = (Buffer.byteLength(readFileSync(OUT)) / 1024).toFixed(0);
console.log(`${OUT}: ${used.length} icons, ${kb}KB`);
